// ── 날짜로 본명수 찾기 유틸 ──────────────────────────────────────
// 실제 구현 시 달의 천문 계산(astronomia 라이브러리)으로 대체 필요
// 아래는 날짜 범위 기반 근사값 계산 (프로토타입/시각화 확인용)
export function getMansionByDate(month, day) {
  for (const m of MANSIONS) {
    const start = m.날짜시작;
    const end = m.날짜종료;
    const inputVal = month * 100 + day;

    // 연도 걸침 처리 (예: 12/25 ~ 1/11)
    if (start.월 > end.월) {
      if (inputVal >= start.월 * 100 + start.일 || inputVal <= end.월 * 100 + end.일) {
        return m;
      }
    } else {
      if (inputVal >= start.월 * 100 + start.일 && inputVal <= end.월 * 100 + end.일) {
        return m;
      }
    }
  }
  return null;
}

