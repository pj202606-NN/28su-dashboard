// ── 전체 운세 생성 ─────────────────────────────────────────────────
export function generateAllFortunes(mansion, allMansions, ilganOhaeng, nianganOhaeng) {
  const categories = ['종합', '연애', '직업', '재물'];
  return {
    오늘: Object.fromEntries(
      categories.map(cat => [cat, generateTodayFortune(mansion, allMansions, ilganOhaeng, cat)])
    ),
    이달: Object.fromEntries(
      categories.map(cat => [cat, generateMonthlyFortune(mansion, ilganOhaeng, cat)])
    ),
    올해: Object.fromEntries(
      categories.map(cat => [cat, generateYearlyFortune(mansion, ilganOhaeng, nianganOhaeng, cat)])
    ),
    분석: generateAnalysis(mansion),
  };
}
