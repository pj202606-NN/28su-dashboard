const SANGSAENG = { 목:'화', 화:'토', 토:'금', 금:'수', 수:'목' };
const SANGGEUK  = { 목:'토', 화:'금', 토:'수', 금:'목', 수:'화' };

export function getOhaengRelation(a, b) {
  if (a === b) return '비화';
  if (SANGSAENG[a] === b) return '상생';
  if (SANGSAENG[b] === a) return '상생받음';
  if (SANGGEUK[a] === b) return '상극';
  if (SANGGEUK[b] === a) return '상극받음';
  return '비화';
}

