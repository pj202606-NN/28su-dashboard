// ── 날짜로 본명수 찾기 ────────────────────────────────────────────
export function getMansionByDate(month, day) {
  const val = month * 100 + day;
  for (const m of MANSION_DATES) {
    const s = m.시작.월 * 100 + m.시작.일;
    const e = m.종료.월 * 100 + m.종료.일;
    if (s > e) {
      if (val >= s || val <= e) return m;
    } else {
      if (val >= s && val <= e) return m;
    }
  }
  return null;
}

// ── 사신별 필터 ───────────────────────────────────────────────────
export function getMansionsBySashin(sashin) {
  return MANSION_DATES.filter(m => m.사신 === sashin);
}

// ── 월별 필터 (시작월 기준) ───────────────────────────────────────
export function getMansionsByMonth(month) {
  return MANSION_DATES.filter(m => m.시작.월 === month || m.종료.월 === month);
}
