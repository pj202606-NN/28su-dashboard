// ── 연도로 천간·지지 계산 유틸 ──────────────────────────────────
export function getYearGapja(year) {
  const cheonganIdx = ((year - 4) % 10 + 10) % 10;
  const jijiIdx     = ((year - 4) % 12 + 12) % 12;
  const gan = CHEONGAN[cheonganIdx];
  const ji  = JIJI[jijiIdx];
  return {
    천간: gan.간,
    천간한자: gan.한자,
    천간오행: gan.오행,
    지지: ji.지,
    지지한자: ji.한자,
    지지오행: ji.오행,
    갑자: gan.간 + ji.지,
    갑자한자: gan.한자 + ji.한자,
  };
}

