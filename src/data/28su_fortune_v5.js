function getGrade(relation, 기본상태) {
  const base = { 상생:"길", 상생받음:"길", 비화:"평", 상극:"주의", 상극받음:"주의" }[relation] || "평";
  if (기본상태 === "대길" && (base === "길" || base === "평")) return "대길";
  if (기본상태 === "흉" && base === "평") return "주의";
  return base;
}

// ── 조사 처리 ──────────────────────────────────────────────────
function hasBatchim(str) {
  const last = str[str.length - 1];
  const code = last.charCodeAt(0);
  if (code < 0xAC00 || code > 0xD7A3) return false;
  return (code - 0xAC00) % 28 !== 0;
}
function eul(w) { return w + (hasBatchim(w) ? "을" : "를"); }
function eun(w) { return w + (hasBatchim(w) ? "은" : "는"); }
function i_(w)  { return w + (hasBatchim(w) ? "이" : "가"); }
function wa(w)  { return w + (hasBatchim(w) ? "과" : "와"); }
function ro(w)  { return w + (hasBatchim(w) ? "으로" : "로"); }

